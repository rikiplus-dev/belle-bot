/* ---------- חיפוש חכם בעברית ---------- */

const FINALS = { ך: 'כ', ם: 'מ', ן: 'נ', ף: 'פ', ץ: 'צ' };
const PREFIXES = 'הובלמכש';
const STOP = new Set(['האם', 'מותר', 'אסור', 'לתת', 'לבל', 'בל', 'אפשר', 'לאכול', 'יכולה', 'לאכל', 'של', 'עם', 'בלי', 'או', 'את', 'על', 'כמו', 'זה', 'מזה', 'מה', 'אם', 'לי', 'לה', 'שלה', 'אכלה', 'אכל', 'אוכל', 'גם', 'כל', 'מאוד', 'קצת', 'כמה']);

export function norm(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/[֑-ׇ]/g, '')
    .replace(/["'`׳״’‘“”]/g, '')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// צורת בסיס: מאחד ריבוי, נקבה וסופיות
export function stem(w) {
  let x = w.replace(/יי/g, 'י').replace(/וו/g, 'ו');
  if (x.length > 4 && x.endsWith('ות')) x = x.slice(0, -2) + 'ה';
  if (x.length > 4 && x.endsWith('ים')) x = x.slice(0, -2);
  if (x.length > 3 && x.endsWith('ה')) x = x.slice(0, -1);
  return x.replace(/[ךםןףץ]/g, (c) => FINALS[c]);
}

// אפשרויות לקריאת מילה: כמו שהיא, ובלי אותיות שימוש (ה, ב, ל...)
function variants(word) {
  const out = new Set([stem(word)]);
  let w = word;
  for (let i = 0; i < 2; i++) {
    if (w.length > 3 && PREFIXES.includes(w[0])) {
      w = w.slice(1);
      out.add(stem(w));
    } else break;
  }
  return [...out];
}

function lev1(a, b) {
  if (a === b) return true;
  if (Math.abs(a.length - b.length) > 1) return false;
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i++;
  if (a.length === b.length) return a.slice(i + 1) === b.slice(i + 1);
  if (a.length > b.length) return a.slice(i + 1) === b.slice(i);
  return b.slice(i + 1) === a.slice(i);
}

// אינדקס כינויים: כל כינוי לרשימת מילות בסיס
const INDEX = [];
for (const f of FOODS) {
  const seen = new Set();
  for (const alias of f.aliases) {
    const toks = norm(alias).split(' ').filter(Boolean).map(stem);
    const key = toks.join(' ');
    if (!toks.length || seen.has(key)) continue;
    seen.add(key);
    INDEX.push({ f, toks });
  }
}

/**
 * מחפש מזון בטקסט חופשי.
 * מחזיר { matches: [food...], level } כש-level הוא הגרוע שבין ההתאמות (אסור גובר על בינוני וגובר על בכיף),
 * או { matches: [], level: null } כשלא נמצא.
 */
export function lookup(text) {
  const words = norm(text).split(' ').filter(Boolean);
  const cand = words.map(variants);
  const used = new Set();
  const found = new Map();

  const take = (entry, idxs) => {
    found.set(entry.f, (found.get(entry.f) || 0) + 1);
    idxs.forEach((i) => used.add(i));
  };

  // 1. התאמה מדויקת, קודם לכינויים הארוכים (שני מילים ויותר)
  const order = [...INDEX].sort((a, b) => b.toks.length - a.toks.length);
  for (const e of order) {
    const idxs = [];
    let ok = true;
    for (const t of e.toks) {
      const i = cand.findIndex((vs, k) => !idxs.includes(k) && vs.includes(t));
      if (i < 0) {
        ok = false;
        break;
      }
      idxs.push(i);
    }
    if (!ok) continue;
    if (e.toks.length === 1 && used.has(idxs[0])) continue;
    take(e, idxs);
  }

  // 2. התאמה מקורבת (טעות כתיב אחת) למילים שעוד לא התאימו
  words.forEach((w, i) => {
    if (used.has(i) || STOP.has(w)) return;
    for (const e of INDEX) {
      if (e.toks.length !== 1 || e.toks[0].length < 4) continue;
      if (cand[i].some((c) => c.length >= 4 && lev1(c, e.toks[0]))) {
        take(e, [i]);
        break;
      }
    }
  });

  const matches = [...found.keys()];
  const rank = { no: 0, mid: 1, ok: 2 };
  matches.sort((a, b) => rank[a.level] - rank[b.level]);
  return { matches, level: matches.length ? matches[0].level : null };
}

export const byLevel = (level) => FOODS.filter((f) => f.level === level);
